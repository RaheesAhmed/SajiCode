import { tool } from "@langchain/core/tools";
import { z } from "zod";
import {
  runVerificationLadder,
  formatLadderResult,
} from "./verification-ladder.js";
import { createPullRequest } from "./deploy-tools.js";

export interface AutoShipResult {
  ok: boolean;
  ladderReport: string;
  e2eReport?: string;
  prUrl?: string;
  output: string;
}

export async function autoShipWithReport(
  projectPath: string,
  input: {
    title: string;
    base?: string;
    e2eBaseUrl?: string;
    skipE2e?: boolean;
  },
): Promise<AutoShipResult> {
  const ladder = await runVerificationLadder(projectPath, {
    ...(input.e2eBaseUrl && !input.skipE2e ? { e2eBaseUrl: input.e2eBaseUrl } : {}),
    ...(input.skipE2e ? { skipE2e: true } : {}),
  });
  const ladderReport = formatLadderResult(ladder);

  if (!ladder.passed) {
    const visual = ladder.visualReviewPath
      ? `\nVisual review: ${ladder.visualReviewPath}`
      : "";
    return {
      ok: false,
      ladderReport,
      output: `${ladderReport}${visual}\n\nPR not created — fix verification failures first.`,
    };
  }

  const e2eRung = ladder.rungs.find((rung) => rung.name === "e2e");
  const e2eReport = e2eRung?.summary;

  const body = [
    "## Verification report",
    "",
    "### Ladder",
    "```",
    ladderReport,
    "```",
    ...(e2eReport ? ["", "### E2E", e2eReport] : []),
    "",
    "_Auto-generated by SajiCode auto_ship_with_report_",
  ].join("\n");

  const pr = await createPullRequest(projectPath, {
    title: input.title,
    body,
    ...(input.base ? { base: input.base } : {}),
  });

  if (!pr.ok) {
    return {
      ok: false,
      ladderReport,
      e2eReport,
      output: `${ladderReport}\n\n❌ PR creation failed:\n${pr.output}`,
    };
  }

  return {
    ok: true,
    ladderReport,
    e2eReport,
    ...(pr.prUrl ? { prUrl: pr.prUrl } : {}),
    output: [
      ladderReport,
      e2eReport ? `\n${e2eReport}` : "",
      "",
      `✅ PR created${pr.prUrl ? `: ${pr.prUrl}` : ""}`,
    ].join("\n"),
  };
}

export function createShipTools(projectPath: string) {
  const shipTool = tool(
    async (input: {
      title: string;
      base?: string;
      e2eBaseUrl?: string;
      skipE2e?: boolean;
    }) => {
      const result = await autoShipWithReport(projectPath, input);
      return result.output;
    },
    {
      name: "auto_ship_with_report",
      description:
        "Run verification ladder (build → tests → smoke), optional E2E, then open a GitHub PR with the report. Requires gh CLI.",
      schema: z.object({
        title: z.string().describe("PR title"),
        base: z.string().optional().describe("Target branch"),
        e2eBaseUrl: z.string().optional().describe("Run Playwright E2E against this URL before PR"),
        skipE2e: z.boolean().optional(),
      }),
    },
  );

  return [shipTool];
}
